@router.post("/api/novos-entrantes/entrada/{id}/interacoes", response_model=dict)
def registrar_interacao_entrada(
    id: int = Path(..., alias="id"),
    payload: dict = Body(...),
):
    """Registra uma interação de contato com o entrante (aparece na timeline)."""
    canal = str(payload.get("canal") or "").strip().upper()
    sentido = str(payload.get("sentido") or "ENVIADO").strip().upper()

    if canal not in _CANAIS_INTERACAO:
        raise HTTPException(
            status_code=400,
            detail=f"canal deve ser um de: {', '.join(sorted(_CANAIS_INTERACAO))}",
        )
    if sentido not in _SENTIDOS_INTERACAO:
        raise HTTPException(status_code=400, detail="sentido deve ser ENVIADO ou RECEBIDO")

    def _limpo(valor: Any) -> Optional[str]:
        texto = str(valor).strip() if valor is not None else ""
        return texto or None

    conn = None
    cursor = None
    try:
        conn = main.get_connection()
        cursor = conn.cursor()
        _garantir_tabela_interacao(cursor)

        cursor.execute(
            "SELECT 1 FROM CLB349328.PORTAL_COMPARTILHAMENTO_ENTRADA WHERE ID_ENTRADA = ?",
            [id],
        )
        if not cursor.fetchone():
            raise HTTPException(status_code=404, detail="Entrada não encontrada")

        cursor.execute(
            """
            INSERT INTO CLB349328.PORTAL_COMPARTILHAMENTO_ENTRADA_INTERACAO
            (
                ID_ENTRADA,
                CANAL,
                SENTIDO,
                CONTATO,
                ASSUNTO,
                OBSERVACAO,
                USUARIO,
                DATA_INTERACAO
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP)
            """,
            [
                id,
                canal,
                sentido,
                _limpo(payload.get("contato")),
                _limpo(payload.get("assunto")),
                _limpo(payload.get("observacao")),
                _limpo(payload.get("usuario")) or "CLB349328",
            ],
        )
        conn.commit()
        return {"success": True}
    except HTTPException:
        raise
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


