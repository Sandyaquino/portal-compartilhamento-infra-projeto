def _somente_digitos(valor: Any, tamanho: Optional[int] = None) -> Optional[str]:
    texto = _texto(valor)
    if not texto:
        return None

    # Corrige valores vindos em notacao cientifica pelo pandas/excel
    try:
        if "e" in texto.lower():
            texto = format(Decimal(texto), "f")
    except (InvalidOperation, ValueError):
        pass

    if texto.endswith(".0"):
        texto = texto[:-2]

    digitos = re.sub(r"\D", "", texto)
    if not digitos:
        return None

    if tamanho and len(digitos) <= tamanho:
        digitos = digitos.zfill(tamanho)

    return digitos


def _inteiro(valor: Any) -> int:
    texto = _texto(valor)
    if not texto:
        return 0

    texto = texto.replace(".", "").replace(",", ".")

    try:
        return int(float(texto))
    except Exception:
        return 0


def _sim_nao(valor):

    texto = _texto(valor)

    if not texto:
        return None

    texto_upper = texto.upper().strip()

    if texto_upper in [
        "S",
        "SIM",
        "TRUE",
        "1",
        "YES"
    ]:
        return "S"

    if texto_upper in [
        "N",
        "NAO",
        "NÃO",
        "FALSE",
        "0",
        "NO"
    ]:
        return "N"

    if texto_upper in [
        "NAO SEI",
        "NÃO SEI"
    ]:
        return "I"

    return None


def _timestamp_forms(valor: Any):
    texto = _texto(valor)
    if not texto:
        return None

    try:
        data = pd.to_datetime(
            texto,
            format="%m/%d/%Y %I:%M %p",
            errors="coerce",
        )

        if pd.isna(data):
            data = pd.to_datetime(texto, errors="coerce")

        if pd.isna(data):
            return None

        return data.to_pydatetime()
    except Exception:
        return None


