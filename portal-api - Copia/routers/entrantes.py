def _somente_data(valor):
    """Normaliza um valor de data/timestamp do HANA (ou string ISO, no caso
    dos testes) para datetime.date, pra comparar prazo x resolução sem se
    importar com o horário."""
    if isinstance(valor, datetime):
        return valor.date()
    if isinstance(valor, date):
        return valor
    if isinstance(valor, str):
        return datetime.fromisoformat(valor[:10]).date()
    return None


@router.get("/api/novos-entrantes/sla-analise", response_model=dict)
def obter_sla_analise():
    """Taxa histórica de cumprimento do prazo atribuído (PRAZO_ANALISE) nos
    entrantes já resolvidos (viraram provedor ou foram descartados). A data
    de resolução vem do primeiro evento de saída da fila de análise em
    HISTORICO_ENTRADA, já que ENTRADA não guarda esse timestamp."""
    conn = None
    cursor = None
    try:
        conn = main.get_connection()
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT E.PRAZO_ANALISE, MIN(H.DATA_EVENTO) AS DATA_RESOLUCAO
            FROM CLB349328.PORTAL_COMPARTILHAMENTO_ENTRADA E
            INNER JOIN CLB349328.PORTAL_COMPARTILHAMENTO_HISTORICO_ENTRADA H
                ON H.ID_ENTRADA = E.ID_ENTRADA
               AND H.STATUS_NOVO IN ('PROVEDOR_CRIADO', 'DESCARTADO')
            WHERE E.PRAZO_ANALISE IS NOT NULL
            GROUP BY E.ID_ENTRADA, E.PRAZO_ANALISE
            """
        )
        linhas = cursor.fetchall()

        total = len(linhas)
        dentro_prazo = sum(
            1 for prazo, resolucao in linhas
            if _somente_data(resolucao) is not None and _somente_data(resolucao) <= _somente_data(prazo)
        )
        fora_prazo = total - dentro_prazo
        taxa = round((dentro_prazo / total) * 100, 1) if total > 0 else 0

        return {
            "total_avaliados": total,
            "dentro_prazo": dentro_prazo,
            "fora_prazo": fora_prazo,
            "taxa_cumprimento_sla": taxa,
        }
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


