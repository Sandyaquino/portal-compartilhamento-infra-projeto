_CANAIS_INTERACAO = {"EMAIL", "LIGACAO", "WHATSAPP", "REUNIAO", "PRESENCIAL", "OUTRO"}
_SENTIDOS_INTERACAO = {"ENVIADO", "RECEBIDO"}


def _garantir_tabela_interacao(cursor) -> None:
    """Cria PORTAL_COMPARTILHAMENTO_ENTRADA_INTERACAO na primeira vez, no mesmo
    espírito do _garantir_tabela usado em outras partes do portal. O DDL
    canônico está em sql/PORTAL_COMPARTILHAMENTO_ENTRADA_INTERACAO.sql."""
    try:
        cursor.execute("SELECT COUNT(*) FROM CLB349328.PORTAL_COMPARTILHAMENTO_ENTRADA_INTERACAO")
        cursor.fetchone()
        return
    except Exception:
        pass

    cursor.execute(
        """
        CREATE COLUMN TABLE CLB349328.PORTAL_COMPARTILHAMENTO_ENTRADA_INTERACAO
        (
            ID_INTERACAO INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
            ID_ENTRADA INTEGER NOT NULL,
            CANAL NVARCHAR(20) NOT NULL,
            SENTIDO NVARCHAR(10) DEFAULT 'ENVIADO',
            CONTATO NVARCHAR(200),
            ASSUNTO NVARCHAR(300),
            OBSERVACAO NVARCHAR(4000),
            USUARIO NVARCHAR(100),
            DATA_INTERACAO LONGDATE CS_LONGDATE,
            PRIMARY KEY (ID_INTERACAO)
        )
        UNLOAD PRIORITY 5 AUTO MERGE
        """
    )


def _criar_processo_para_provedor(cursor, id_provedor: int, user: str) -> Tuple[int, str]:
    """Cria um processo novo (etapa inicial, jornada em andamento) para um
    provedor já existente. Reutilizado tanto pelo fluxo de criação de
    processo a partir de um Entrante quanto pela criação direta de um novo
    processo/PN para um provedor que já tem cadastro (POST /api/provedores/{id}/processos).
    Não faz commit - quem chama decide quando confirmar a transação."""
    numero_protocolo_temporario = f"TEMP-{id_provedor}-{datetime.now().strftime('%Y%m%d%H%M%S%f')}"

    cursor.execute(
        """
        INSERT INTO CLB349328.PORTAL_COMPARTILHAMENTO_PROCESSO
        (
            ID_PROVEDOR,
            NUMERO_PROTOCOLO,
            TIPO_PROCESSO,
            STATUS_ATUAL,
            ETAPA_ATUAL,
            DT_ABERTURA
        )
        VALUES
        (
            ?,
            ?,
            'REGULARIZACAO_CADASTRAL',
            'ABERTO',
            1,
            CURRENT_TIMESTAMP
        )
        """,
        [id_provedor, numero_protocolo_temporario],
    )

    # pyhdb não possui cursor.lastrowid.
    # Primeiro tenta recuperar o ID da identidade gerada na sessão.
    try:
        cursor.execute("""
            SELECT CURRENT_IDENTITY_VALUE()
            FROM DUMMY
        """)
        resultado_id = cursor.fetchone()
        id_processo = resultado_id[0] if resultado_id else None
    except Exception:
        id_processo = None

    # Fallback: buscar o processo criado para o provedor com o protocolo temporário.
    if not id_processo:
        cursor.execute(
            """
            SELECT MAX(ID_PROCESSO)
            FROM CLB349328.PORTAL_COMPARTILHAMENTO_PROCESSO
            WHERE ID_PROVEDOR = ?
              AND NUMERO_PROTOCOLO = ?
            """,
            [id_provedor, numero_protocolo_temporario],
        )
        resultado_id = cursor.fetchone()
        id_processo = resultado_id[0] if resultado_id else None

    if not id_processo:
        raise HTTPException(
            status_code=500,
            detail="Não foi possível recuperar o ID do processo criado."
        )

    numero_protocolo = f"{datetime.now().year}-{int(id_processo):06d}"

    cursor.execute(
        """
        UPDATE CLB349328.PORTAL_COMPARTILHAMENTO_PROCESSO
           SET NUMERO_PROTOCOLO = ?
         WHERE ID_PROCESSO = ?
        """,
        [numero_protocolo, id_processo],
    )

    cursor.execute(
        """
        INSERT INTO CLB349328.PORTAL_COMPARTILHAMENTO_JORNADA
        (
            ID_PROCESSO,
            ID_ETAPA,
            STATUS_ETAPA,
            DATA_ENTRADA_ETAPA,
            RESPONSAVEL_ATUAL,
            CREATED_AT,
            CREATED_BY
        )
        VALUES
        (
            ?,
            1,
            'EM_ANDAMENTO',
            CURRENT_TIMESTAMP,
            ?,
            CURRENT_TIMESTAMP,
            ?
        )
        """,
        [id_processo, user, user],
    )

    return int(id_processo), numero_protocolo


