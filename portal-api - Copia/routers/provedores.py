TB_SOLICITACAO_ACAO = f"{SCHEMA_SOLICITACAO}.PORTAL_COMPARTILHAMENTO_SOLICITACAO_ACAO"


def _somente_digitos_sql(coluna: str) -> str:
    """Normaliza um CNPJ pra comparação, tirando pontuação - o CNPJ pode
    estar salvo formatado diferente entre PROVEDOR e OPERADORA (tabelas
    independentes historicamente, ver nota em listar_postes_do_provedor)."""
    return f"REPLACE(REPLACE(REPLACE({coluna}, '.', ''), '/', ''), '-', '')"

# =====================================================
# Contratos: provedores que já concluíram a jornada + solicitação de ação a
# times de Técnico, Negociação e Comercial. Ver
# sql_nova_tabela_solicitacao_acao.txt para o schema da tabela nova - ela é
# criada sozinha na primeira chamada (mesmo padrão de TB_ACAO em postes.py e
# da tabela de OTP em auth.py), não precisa rodar migração manual.
# =====================================================

CATALOGO_TIPOS_ACAO = {
    "REMOCAO": {"label": "Solicitar remoção", "time": "TECNICO"},
    "NOTIFICACAO": {"label": "Encaminhar notificação ao provedor", "time": "COMERCIAL"},
    "COBRANCA": {"label": "Solicitar cobrança", "time": "NEGOCIACAO"},
    "DESFAZER_CONTRATO": {"label": "Solicitar desfazimento do contrato", "time": "COMERCIAL"},
    "OUTRO": {"label": "Outra solicitação", "time": "COMERCIAL"},
}
TIMES_RESPONSAVEL_VALIDOS = {"TECNICO", "NEGOCIACAO", "COMERCIAL"}
STATUS_SOLICITACAO_VALIDOS = {"ABERTA", "EM_ANDAMENTO", "CONCLUIDA", "CANCELADA"}


def _solicitacoes_garantir_tabela(cursor) -> None:
    try:
        cursor.execute(f"SELECT COUNT(*) FROM {TB_SOLICITACAO_ACAO}")
        cursor.fetchone()
        return
    except Exception:
        pass

    cursor.execute(f"""
        CREATE COLUMN TABLE {TB_SOLICITACAO_ACAO}
        (
            "ID_SOLICITACAO" INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
            "ID_PROVEDOR" INTEGER NOT NULL,
            "ID_PROCESSO" INTEGER,
            "ID_ACAO_POSTE" INTEGER,
            "TIPO_ACAO" NVARCHAR(30) NOT NULL,
            "TIME_RESPONSAVEL" NVARCHAR(20) NOT NULL,
            "DESCRICAO" NVARCHAR(2000),
            "PRIORIDADE" NVARCHAR(10) DEFAULT 'MEDIA',
            "STATUS" NVARCHAR(20) DEFAULT 'ABERTA',
            "SOLICITADO_POR" NVARCHAR(100),
            "DATA_SOLICITACAO" LONGDATE CS_LONGDATE,
            "RESPONSAVEL_EXECUCAO" NVARCHAR(100),
            "DATA_CONCLUSAO" LONGDATE CS_LONGDATE,
            "OBSERVACAO_CONCLUSAO" NVARCHAR(2000),
            "CREATED_AT" LONGDATE CS_LONGDATE,
            "UPDATED_AT" LONGDATE CS_LONGDATE,
            PRIMARY KEY ("ID_SOLICITACAO")
        )
        UNLOAD PRIORITY 5 AUTO MERGE
    """)


class SolicitacaoAcaoCreate(BaseModel):
    tipo_acao: str
    descricao: Optional[str] = None
    prioridade: Optional[str] = "MEDIA"
    id_processo: Optional[int] = None
    time_responsavel: Optional[str] = None
    barramentos: Optional[List[str]] = None


class SolicitacaoAcaoUpdate(BaseModel):
    status: str
    observacao_conclusao: Optional[str] = None
    responsavel_execucao: Optional[str] = None


@router.get("/api/provedores", response_model=List[dict])
def listar_provedores():
    """Provedores que já percorreram toda a jornada (têm ao menos um
    processo concluído) - base da tela Comercial > Contratos."""
    conn = None
    cursor = None
    try:
        conn = main.get_connection()
        cursor = conn.cursor()

        cursor.execute(f"""
            SELECT
                P.ID_PROVEDOR, P.CNPJ, P.RAZAO_SOCIAL, P.NOME_FANTASIA,
                P.RESPONSAVEL, P.EMAIL, P.TELEFONE, P.STATUS_CADASTRO,
                COUNT(PR.ID_PROCESSO) AS TOTAL_PROCESSOS,
                MAX(PR.DT_CONCLUSAO) AS ULTIMA_CONCLUSAO
            FROM {TB_PROVEDOR_SOLICITACAO} P
            INNER JOIN {TB_PROCESSO_SOLICITACAO} PR
                ON PR.ID_PROVEDOR = P.ID_PROVEDOR AND PR.STATUS_ATUAL = 'CONCLUIDO'
            GROUP BY P.ID_PROVEDOR, P.CNPJ, P.RAZAO_SOCIAL, P.NOME_FANTASIA,
                     P.RESPONSAVEL, P.EMAIL, P.TELEFONE, P.STATUS_CADASTRO
            ORDER BY P.RAZAO_SOCIAL ASC
        """)
        colunas = [c[0] for c in cursor.description]
        return [
            {colunas[i]: _processos_json_value(v) for i, v in enumerate(row)}
            for row in cursor.fetchall()
        ]
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@router.get("/api/provedores/{id}/postes", response_model=List[dict])
def listar_postes_do_provedor(id: int = Path(..., alias="id")):
    """Postes/ocupações deste provedor no Mapa de Postes - usado pelo
    modal de 'Solicitar Ação' quando o tipo é Remoção, pra deixar escolher
    quais postes são o alvo.

    PROVEDOR (jornada comercial) e OPERADORA (mapa de postes) são tabelas
    independentes historicamente; aqui elas são ligadas pelo CNPJ, tolerando
    diferença de formatação (com/sem pontuação) entre as duas."""
    conn = None
    cursor = None
    try:
        conn = main.get_connection()
        cursor = conn.cursor()

        cursor.execute(f"SELECT CNPJ FROM {TB_PROVEDOR_SOLICITACAO} WHERE ID_PROVEDOR = ?", [id])
        linha = cursor.fetchone()
        if not linha:
            raise HTTPException(status_code=404, detail="Provedor não encontrado")
        cnpj = linha[0]

        cursor.execute(
            f"""
            SELECT O."BARRAMENTO", O."BOARD_NAME", P."X", P."Y"
            FROM {_TB_OCUPACAO} O
            INNER JOIN {_TB_OPERADORA} OP ON {_somente_digitos_sql('OP."CNPJ"')} = {_somente_digitos_sql('?')}
            LEFT JOIN {_TB_POSTE} P ON P."BARRAMENTO" = O."BARRAMENTO"
            WHERE O."BARRAMENTO" IS NOT NULL
            ORDER BY O."BOARD_NAME"
            """,
            [cnpj],
        )
        colunas = [c[0] for c in cursor.description]
        return [
            {colunas[i]: _processos_json_value(v) for i, v in enumerate(row)}
            for row in cursor.fetchall()
        ]
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


