-- ---------------------------------------------------------------------
-- 4) CARTEIRA (cabeçalho)
-- ---------------------------------------------------------------------
CREATE COLUMN TABLE "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA"
(
    "ID_CARTEIRA"      INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
    "TITULO"           NVARCHAR(200),
    "FREQUENCIA"       NVARCHAR(10)  DEFAULT 'SEMANAL',  -- DIARIA | SEMANAL | MENSAL
    "DATA_INICIO"      DATE NOT NULL,
    "DATA_FIM"         DATE NOT NULL,
    "MODO"             NVARCHAR(12)  DEFAULT 'AUTOMATICA', -- MANUAL | AUTOMATICA
    "ESTRATEGIA"       NVARCHAR(40),                    -- -> CARTEIRA_ESTRATEGIA.CODIGO (só no modo AUTOMATICA)
    "ID_EPS"           INTEGER,
    "QTD_POSTES_DIA"   INTEGER DEFAULT 12,
    "QTD_OS"           INTEGER DEFAULT 0,
    "QTD_EQUIPES"      INTEGER DEFAULT 0,
    "STATUS"           NVARCHAR(15) DEFAULT 'RASCUNHO', -- RASCUNHO | PUBLICADA | CONCLUIDA | CANCELADA
    "PARAMETROS_JSON"  NVARCHAR(4000),                  -- eco dos parâmetros usados na geração
    "CREATED_AT"       LONGDATE CS_LONGDATE,
    "CREATED_BY"       NVARCHAR(100),
    "UPDATED_AT"       LONGDATE CS_LONGDATE,
    PRIMARY KEY ("ID_CARTEIRA")
)
UNLOAD PRIORITY 5 AUTO MERGE;

CREATE INDEX "IX_CARTEIRA_STATUS" ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA" ("STATUS");
CREATE INDEX "IX_CARTEIRA_INICIO" ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA" ("DATA_INICIO");


-- ---------------------------------------------------------------------
-- 5) MUNICÍPIOS/LOCALIDADES no escopo da carteira
-- ---------------------------------------------------------------------
CREATE COLUMN TABLE "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_ESCOPO"
(
    "ID"               INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
    "ID_CARTEIRA"      INTEGER NOT NULL,
    "MUNICIPIO"        NVARCHAR(120),
    "NU_LOCALIDADE_ID" BIGINT,                          -- nulo = município inteiro
    PRIMARY KEY ("ID")
)
UNLOAD PRIORITY 5 AUTO MERGE;

CREATE INDEX "IX_CARTESCOPO_CARTEIRA" ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_ESCOPO" ("ID_CARTEIRA");


-- ---------------------------------------------------------------------
-- 6) ORDENS DE SERVIÇO da carteira (1 linha por poste/dia/equipe)
-- ---------------------------------------------------------------------
CREATE COLUMN TABLE "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_OS"
(
    "ID_CARTEIRA_OS"  INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
    "ID_CARTEIRA"     INTEGER NOT NULL,
    "SEQ"             INTEGER,                          -- ordem global na carteira

    "NU_PG_ID"        BIGINT,                           -- -> BASE_POSTE.NU_PG_ID
    "DE_BARRAMENTO"   NVARCHAR(50),
    "MUNICIPIO"       NVARCHAR(120),
    "LOCALIDADE"      NVARCHAR(120),
    "LATITUDE"        DECIMAL(18,10),
    "LONGITUDE"       DECIMAL(18,10),
    "TEM_PROVEDOR"    NVARCHAR(1) DEFAULT 'N',

    "ID_EQUIPE"       INTEGER,
    "NOME_EQUIPE"     NVARCHAR(80),
    "EPS"             NVARCHAR(150),

    "DATA_PREVISTA"   DATE,
    "DIA_INDICE"      INTEGER,                          -- 1..N dias úteis da carteira
    "ORDEM_NO_DIA"    INTEGER,                          -- sequência da rota naquele dia

    "ESTRATEGIA"      NVARCHAR(40),
    "SCORE"           DECIMAL(9,4),                     -- pontuação da estratégia (evidência)
    "MOTIVO"          NVARCHAR(300),                    -- porque este poste entrou

    "STATUS"          NVARCHAR(15) DEFAULT 'PLANEJADA', -- PLANEJADA | EM_ROTA | EXECUTADA | CANCELADA
    "LINK_GMAPS"      NVARCHAR(300),
    "LINK_WAZE"       NVARCHAR(300),
    "EXECUTADO_EM"    LONGDATE CS_LONGDATE,
    "OBSERVACAO"      NVARCHAR(1000),
    "CREATED_AT"      LONGDATE CS_LONGDATE,
    PRIMARY KEY ("ID_CARTEIRA_OS")
)
UNLOAD PRIORITY 5 AUTO MERGE;

CREATE INDEX "IX_CARTOS_CARTEIRA"  ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_OS" ("ID_CARTEIRA");
CREATE INDEX "IX_CARTOS_EQUIPE"    ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_OS" ("ID_EQUIPE");
CREATE INDEX "IX_CARTOS_DATA"      ON "CLB349328"."PORTAL_COMPARTILHAMENTO_CARTEIRA_OS" ("DATA_PREVISTA");


