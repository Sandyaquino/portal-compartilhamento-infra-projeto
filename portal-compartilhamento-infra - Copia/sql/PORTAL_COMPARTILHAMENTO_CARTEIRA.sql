-- =====================================================================
--  Carteira de Serviço das Equipes de Campo
--
--  Um "gerador de carteira" monta o roteiro de trabalho das equipes de
--  campo (diária / semanal / mensal). Os postes podem ser escolhidos a
--  mão OU gerados automaticamente por uma das ESTRATÉGIAS (lógicas de
--  priorização - ver PORTAL_COMPARTILHAMENTO_CARTEIRA_ESTRATEGIA).
--
--  A alocação respeita:
--   - EPS e equipes escolhidas
--   - quantidade de postes por dia
--   - município(s) / localidade(s) de atuação
--   - otimização de rota na semana: a equipe não pula de município a cada
--     dia; consome um município antes de ir para o próximo, e a ordem dos
--     postes no dia segue vizinho-mais-próximo.
--
--  Schema de trabalho: ajuste "CLB349328" se o seu for outro.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1) EPS (Empresa Prestadora de Serviço)
-- ---------------------------------------------------------------------
CREATE COLUMN TABLE "CLB349328"."PORTAL_COMPARTILHAMENTO_EPS"
(
    "ID_EPS"        INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
    "NOME"          NVARCHAR(150) NOT NULL,
    "CNPJ"          NVARCHAR(20),
    "TIPO_SERVICO"  NVARCHAR(20) DEFAULT 'AMBOS',   -- FISCALIZACAO | REMOCAO | AMBOS
    "ATIVO"         NVARCHAR(1)  DEFAULT 'S',
    "CREATED_AT"    LONGDATE CS_LONGDATE,
    PRIMARY KEY ("ID_EPS")
)
UNLOAD PRIORITY 5 AUTO MERGE;


-- ---------------------------------------------------------------------
-- 2) EQUIPE DE CAMPO
-- ---------------------------------------------------------------------
CREATE COLUMN TABLE "CLB349328"."PORTAL_COMPARTILHAMENTO_EQUIPE_CAMPO"
(
    "ID_EQUIPE"      INTEGER CS_INT GENERATED BY DEFAULT AS IDENTITY,
    "ID_EPS"         INTEGER NOT NULL,
    "NOME"           NVARCHAR(80) NOT NULL,          -- ex.: "Turma A"
    "ENCARREGADO"    NVARCHAR(120),
    "MUNICIPIO_BASE" NVARCHAR(120),                  -- ponto de partida da rota
    "LATITUDE_BASE"  DECIMAL(18,10),
    "LONGITUDE_BASE" DECIMAL(18,10),
    "TIPO"           NVARCHAR(20) DEFAULT 'FISCALIZACAO', -- FISCALIZACAO | REMOCAO
    "ATIVO"          NVARCHAR(1)  DEFAULT 'S',
    "CREATED_AT"     LONGDATE CS_LONGDATE,
    PRIMARY KEY ("ID_EQUIPE")
)
UNLOAD PRIORITY 5 AUTO MERGE;

CREATE INDEX "IX_EQUIPECAMPO_EPS" ON "CLB349328"."PORTAL_COMPARTILHAMENTO_EQUIPE_CAMPO" ("ID_EPS");


